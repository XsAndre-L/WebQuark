import { mkdir, mkdtemp, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { parseStableVersion } from '../versioning/stable-version.js';
import { contentHash, loadReleaseAssets } from './assets.js';
import { parseReleaseSummaries } from './summaries.js';
import { capturePreviewAssetOptions, revalidateCapturePreview, type CapturePreview } from './preview.js';

import { projectPath, requireNotesConfig, validateChangelogConfig, type ChangelogConfig } from '../config/index.js';

/** Validate all input before touching the generator-owned directory. */
export async function generateWhatsNew(
  config: ChangelogConfig,
  options: { includeUnreleased?: boolean; environmentType?: string; capturePreview?: CapturePreview } = {},
): Promise<{
  outputDirectory: string;
  feedUrl: string;
  releases: number;
}> {
  requireNotesConfig(config);
  await validateChangelogConfig(config);
  const includeUnreleased = resolveUnreleasedPreview(options.includeUnreleased ? ['--include-unreleased'] : [], options.environmentType);
  const packageJson = JSON.parse(
    await readFile(projectPath(config, config.sourceManifest), 'utf8'),
  ) as { version?: unknown };
  const builtVersion = parseStableVersion(packageJson.version, 'Root package.json version');
  const releases = parseReleaseSummaries(
    await readFile(projectPath(config, config.changelog), 'utf8'),
    builtVersion.value,
    includeUnreleased,
  );
  const preview = options.capturePreview ? await revalidateCapturePreview(config, options.capturePreview) : undefined;
  if (preview && !includeUnreleased) throw new Error('Capture preview requires includeUnreleased in the managed build.');
  const imageFiles = await loadReleaseAssets(config, releases, preview ? capturePreviewAssetOptions(preview) : {});
  const feed = `${JSON.stringify({ releases }, null, 2)}\n`;
  const feedName = `releases.${contentHash(feed)}.json`;
  const feedUrl = `${config.feedPublicPrefix}/${feedName}`;
  const outputDirectory = projectPath(config, config.feedOutputDirectory);
  await mkdir(dirname(outputDirectory), { recursive: true });
  const staging = await mkdtemp(`${outputDirectory}.staging-`);
  try {
    await mkdir(resolve(staging, 'images'));
    await writeFile(resolve(staging, feedName), feed, 'utf8');
    await writeFile(
      resolve(staging, 'feed-url.ts'),
      `// Generated by WebQuark changelog tooling. Do not edit.\nexport const WHAT_S_NEW_FEED_URL = ${JSON.stringify(feedUrl)};\n`,
      'utf8',
    );
    for (const [path, content] of imageFiles) {
      await writeFile(resolve(staging, path), content);
    }
    // This isolated folder belongs only to this generator; runtime config and other output stay outside it.
    await rm(outputDirectory, { recursive: true, force: true });
    await rename(staging, outputDirectory);
  } finally {
    await rm(staging, { recursive: true, force: true });
  }
  return { outputDirectory, feedUrl, releases: releases.length };
}

export function resolveUnreleasedPreview(args: readonly string[], environmentType?: string): boolean {
  if (args.some(arg => arg !== '--include-unreleased') || args.length > 1) throw new Error('prepare:whats-new accepts only --include-unreleased for development previews.');
  if (environmentType && !['dev', 'prod', 'prod-rehearsal'].includes(environmentType)) throw new Error('prepare:whats-new ENVIRONMENT_TYPE must be dev, prod or prod-rehearsal.');
  if (environmentType === 'prod' || environmentType === 'prod-rehearsal') return false;
  return args.includes('--include-unreleased') || environmentType === 'dev';
}


