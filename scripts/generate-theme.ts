import { dimensionTokens, themeGroups, controls, rem } from '../src/theme/tokens';
import { writeFileSync } from 'node:fs';

const generated = '/* Generated by scripts/generate-theme.ts. */\n';
const groups = [{ category: 'Spacing & Control Sizing', tokens: dimensionTokens }, ...themeGroups];
const tokens = themeGroups.flatMap(group => group.tokens);
const declarations = (mode: 'light' | 'dark') => tokens.filter(token => token[mode] !== undefined).map(token => `  ${token.name}: ${token[mode]};`).join('\n');
writeFileSync('src/theme/tokens.css', generated + ':root {\n' + groups.map(group => `  /* ${group.category} */\n` + group.tokens.map(t => `  ${t.name}: ${t.value};`).join('\n')).join('\n\n') + '\n}\n\n' +
  '@media (prefers-color-scheme: light) {\n  :root {\n' + declarations('light') + '\n  }\n}\n\n' +
  "[data-theme='light'] {\n" + declarations('light') + "\n}\n\n[data-theme='dark'] {\n" + declarations('dark') + '\n}\n');
let css = generated + ':host {\n  min-width: 0;\n';
for (const [metric, value] of Object.entries(controls.md)) {
  css += `  --_q-control-${metric}: var(--q-context-control-${metric}, var(--q-control-${metric}-md, ${rem(value)}));\n`;
}
css += '}\n';
for (const [size, metrics] of Object.entries(controls)) {
  css += `.size-${size} {\n`;
  for (const [metric, value] of Object.entries(metrics)) css += `  --_q-control-${metric}: var(--q-control-${metric}-${size}, ${rem(value)});\n`;
  css += '}\n';
}
writeFileSync('src/theme/control.css', css);
writeFileSync('docs/theme-tokens.md', '# Theme tokens\n\nGenerated from `src/theme/tokens.ts`. Dimensions use rem; default root size is 16px. Optional component overrides remain unset and are documented with each component.\n\n' + groups.map(group => `## ${group.category}\n\n| Token | Default | Light override |\n| --- | --- | --- |\n` + group.tokens.map(t => `| \`${t.name}\` | \`${t.value}\` | ${'light' in t ? `\`${t.light}\`` : '—'} |`).join('\n')).join('\n\n') + '\n');
